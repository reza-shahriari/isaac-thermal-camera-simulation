#!/usr/bin/env python3
"""Build the project site — everything this repository knows, as one browsable thing.

    python scripts/build_site.py                 # build into _site/
    python scripts/build_site.py --serve         # build, then serve it on http://localhost:8000
    python scripts/build_site.py --no-media      # skip the gallery encode (documents only, fast)
    python scripts/build_site.py --out DIR       # somewhere else
    python scripts/build_site.py --outputs DIR   # a different render tree ($IRSIM_OUTPUTS)

The site is static, has no build dependency outside this repository, and is published by pushing
`_site/` to the `gh-pages` branch (`make site-publish`). It is built from three kinds of source:

1. **The documents that already exist** — `docs/physics-model.md`, the roadmap, every ADR, the
   validation reports, the changelog, README and CLAUDE.md. Rendered, not duplicated: the site
   cannot drift from them because it has no copy of them.
2. **The repository itself** — the module map, the configuration catalogue and the numbers on the
   front page are measured at build time (`scripts/site_survey.py`).
3. **The renders** — `site/gallery.yaml` names the frames and clips worth showing and
   `scripts/site_gallery.py` re-encodes them for the web. `outputs/` is 8 GB and gitignored, so
   the site carries a web-sized subset and says so.

Output is a plain directory of HTML with relative links throughout, which works both at
`file://`/localhost and under the `/<repo>/` prefix GitHub project pages are served from.
"""

