# ---------------------------------------------------------------------------------------------
# link resolution


class Resolver:
    """Rewrites a document's own links so they point at the built site.

    A link that names another rendered document becomes a relative site link; one that names a file
    in the repository (a module, a config, a script) becomes a link to it on GitHub, so following
    a citation from the physics model lands on the code that implements it. Anything else is left
    exactly as written.
    """

    def __init__(self, pages: dict[str, str], repo: pathlib.Path) -> None:
        self.pages = pages
        self.repo = repo
        #: Links naming a document that is neither a page nor a file in the tree. These are dead
        #: references in the source documents, so the build reports them instead of quietly
        #: publishing a 404 -- a renamed ADR is the usual cause.
        self.unresolved: set[tuple[str, str]] = set()

    def for_page(self, source: str | None, url: str):  # -> Callable[[str], str]
        base = posixpath.dirname(source) if source else ""

        def resolve(href: str) -> str:
            if not href or href.startswith(("http://", "https://", "mailto:", "#")):
                return href
            path, _, fragment = href.partition("#")
            fragment = f"#{fragment}" if fragment else ""
            target = posixpath.normpath(posixpath.join(base, path)) if path else source or ""
            if target in self.pages:
                return relative(url, self.pages[target]) + fragment
            if (self.repo / target).exists():
                return f"{GITHUB}/blob/main/{target}{fragment}"
            if path.endswith(".md"):
                self.unresolved.add((source or url, href))
            return href

        return resolve


# ---------------------------------------------------------------------------------------------
# pages built from documents


def document_page(
    repo: pathlib.Path,
    source: str,
    url: str,
    title: str,
    group: str,
    subtitle: str,
    resolver: Resolver,
) -> Page:
    text = (repo / source).read_text(encoding="utf-8")
    text = _strip_leading_title(text)
    doc = site_markdown.render(text, resolver.for_page(source, url))
    return Page(
        url=url,
        title=title,
        subtitle=subtitle,
        body=doc.html,
        nav_section=group,
        headings=doc.headings,
        source=source,
        search_text=_plain(doc.html),
    )


def _strip_leading_title(text: str) -> str:
    """Drop a document's own `# Title` — the page head already shows one."""
    lines = text.split("\n")
    for index, line in enumerate(lines):
        if line.startswith("# "):
            return "\n".join(lines[:index] + lines[index + 1 :])
        if line.strip():
            break
    return text


def _plain(markup: str) -> str:
    """Tags out, entities out: what the search index stores."""
    text = re.sub(r"<(script|style)[^>]*>.*?</\1>", " ", markup, flags=re.S)
    text = re.sub(r"<[^>]+>", " ", text)
    return re.sub(r"\s+", " ", html.unescape(text)).strip()


def decision_index(adrs: list[site_survey.Adr], url: str, group: str, blurb: str) -> Page:
    rows = []
    for adr in sorted(adrs, key=lambda a: a.number):
        status = adr.status.split()[0].rstrip(".,")
        rows.append(
            f'<tr data-status="{html.escape(status.lower())}">'
            f'<td class="nowrap">{adr.number}</td>'
            f'<td><a href="{relative(url, adr.url)}">{html.escape(adr.title)}</a></td>'
            f"<td>{html.escape(adr.status)}</td>"
            f'<td class="nowrap">{html.escape(adr.date)}</td></tr>'
        )
    body = [
        f"<p>{site_markdown.render(blurb).html[3:-4]}</p>",
        '<p class="filterline"><input id="adr-filter" type="search" placeholder="Filter '
        f'{len(adrs)} decisions…" aria-label="Filter decisions"></p>',
        "<div class='table-wrap'><table id=\"adr-table\"><thead><tr><th>#</th><th>decision</th>"
        "<th>status</th><th>date</th></tr></thead><tbody>",
        *rows,
        "</tbody></table></div>",
    ]
    return Page(
        url=url,
        title="Decision log",
        subtitle=f"{len(adrs)} architecture decision records.",
        body="\n".join(body),
        nav_section=group,
        wide=True,
        search_text=" ".join(a.title for a in adrs),
    )


def collection_index(pages: list[Page], url: str, title: str, group: str, blurb: str) -> Page:
    cards = []
    for page in sorted(pages, key=lambda p: p.title):
        summary = html.escape(page.search_text[:220])
        cards.append(
            f'<a class="card" href="{relative(url, page.url)}"><h3>{html.escape(page.title)}</h3>'
            f"<p>{summary}…</p></a>"
        )
    body = [
        f"<p>{site_markdown.render(blurb).html[3:-4]}</p>",
        '<div class="cards">',
        *cards,
        "</div>",
    ]
    return Page(
        url=url,
        title=title,
        subtitle=f"{len(pages)} document(s).",
        body="\n".join(body),
        nav_section=group,
        wide=True,
    )


