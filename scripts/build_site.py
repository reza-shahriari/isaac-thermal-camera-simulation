def build(out: pathlib.Path, outputs: pathlib.Path, *, media: bool = True) -> dict[str, int]:
    repo = REPO
    out.mkdir(parents=True, exist_ok=True)

    adr_paths = sorted((repo / "docs" / "decisions").glob("*.md"))
    url_map: dict[str, str] = {source: url for source, url, *_ in DOCUMENTS}
    for path in adr_paths:
        url_map[f"docs/decisions/{path.name}"] = f"decisions/{path.stem}/"
    collection_pages: dict[str, list[pathlib.Path]] = {}
    for directory, url, *_ in COLLECTIONS:
        if directory == "docs/decisions":
            collection_pages[directory] = adr_paths
            continue
        paths = sorted((repo / directory).glob("*.md"))
        collection_pages[directory] = paths
        for path in paths:
            url_map[f"{directory}/{path.name}"] = f"{url}{path.stem}/"
    resolver = Resolver(url_map, repo)

    pages: list[Page] = []
    for source, url, title, group, subtitle in DOCUMENTS:
        pages.append(document_page(repo, source, url, title, group, subtitle, resolver))

    adrs: list[site_survey.Adr] = []
    for directory, url, title, group, blurb in COLLECTIONS:
        made: list[Page] = []
        for path in collection_pages[directory]:
            source = f"{directory}/{path.name}"
            page_url = url_map[source]
            page = document_page(repo, source, page_url, path.stem, group, "", resolver)
            if page.headings and page.headings[0].level == 1:
                page.title = page.headings[0].text
            else:
                doc_title = site_markdown.render(
                    (repo / source).read_text(encoding="utf-8").split("\n")[0].lstrip("# ")
                )
                page.title = _plain(doc_title.html) or path.stem
            if directory == "docs/decisions":
                adrs.append(site_survey.adr_meta(path, page_url))
            made.append(page)
        pages.extend(made)
        if directory == "docs/decisions":
            pages.append(decision_index(adrs, url, group, blurb))
        else:
            pages.append(collection_index(made, url, title, group, blurb))

    gallery = site_gallery.GalleryBuilder(
        repo / "site" / "gallery.yaml",
        outputs,
        out / "media",
        media_prefix="../media/",
        encode=media,
    ).build("gallery/")
    pages.append(gallery.page)

    pages.append(site_survey.code_map(repo))
    pages.append(site_survey.config_catalogue(repo))

    plan = site_survey.plan(repo)
    stats = {
        "modules": len(site_survey.modules(repo)),
        "tests": sum(t for _, t, _ in site_survey.test_counts(repo).values()),
        "adrs": len(adrs),
        "configs": len(list((repo / "configs").rglob("*.yaml"))),
        "spec_sections": len({s for m in site_survey.modules(repo) for s in m.sections}),
        "steps_done": plan.done if plan else 0,
        "steps_total": plan.total if plan else 0,
    }
    hero = None
    hero_asset = next(
        (a for a in gallery.assets if a.url.endswith("quad_pointwise_vs_objectwise.mp4")), None
    )
    if hero_asset:
        hero = f"media/{hero_asset.url}"
    pages.insert(0, home_page(repo, stats, plan, hero))

    groups = nav_groups(pages)
    built = dt.datetime.now(dt.UTC).strftime("%Y-%m-%d %H:%M UTC")
    commit = site_survey.commit()
    for page in pages:
        target = out / page.out_path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(render_page(page, groups, built=built, commit=commit), encoding="utf-8")

    write_search(out, pages)
    copy_assets(repo, out)
    (out / ".nojekyll").write_text("", encoding="utf-8")

    total = sum(f.stat().st_size for f in out.rglob("*") if f.is_file())
    return {
        "unresolved": sorted(resolver.unresolved),
        # The headline figures, returned so a caller (and the test) can check what was published
        # against what was counted, in one run: this tree is edited by several sessions at once,
        # so recounting afterwards races against them.
        "stats": stats,
        "pages": len(pages),
        "media": len(gallery.assets),
        "missing": len(gallery.missing),
        "bytes": total,
        "media_bytes": sum(a.bytes for a in gallery.assets),
        "source_bytes": sum(a.source_bytes for a in gallery.assets),
    }


def nav_groups(pages: list[Page]) -> list[NavGroup]:
    """The sidebar: one group per section, collections collapsed to their index."""
    wanted = {
        "Start": ["", "gallery/", "status/"],
        "Demos": [],
        "Physics": ["physics/", "spec-issues/"],
        "Plan": ["roadmap/", "decisions/", "changelog/"],
        "Evidence": ["validation/", "research/"],
        "Reference": ["code/", "configs/", "guide/"],
    }
    titles = {page.url: page.title for page in pages}
    #: Sidebar labels, where a page's own title is longer than a nav entry should be.
    titles.update({"gallery/": "Demo gallery", "": "Overview"})
    groups: list[NavGroup] = []
    for name in NAV_ORDER:
        urls = wanted.get(name, [])
        items = [NavItem(titles.get(url, url), url) for url in urls if url in titles]
        if name == "Start":
            items = [NavItem("Overview", ""), *[i for i in items if i.url]]
        if items:
            groups.append(NavGroup(name, items))
    return groups


def write_search(out: pathlib.Path, pages: list[Page]) -> None:
    """A flat index of pages and their headings.

    Small enough to ship whole and search inside the page, which is why the site needs no search
    service and works from `file://`.
    """
    index = []
    for page in pages:
        index.append(
            {
                "t": page.title,
                "u": page.url,
                "s": page.nav_section,
                "h": [{"t": h.text, "a": h.slug} for h in page.headings if h.level <= 3][:60],
                "x": (page.search_text or _plain(page.body))[:400],
            }
        )
    (out / "search.json").write_text(json.dumps(index, separators=(",", ":")), encoding="utf-8")


def copy_assets(repo: pathlib.Path, out: pathlib.Path) -> None:
    target = out / "assets"
    target.mkdir(parents=True, exist_ok=True)
    for path in sorted((repo / "site" / "assets").glob("*")):
        if path.is_file():
            shutil.copy2(path, target / path.name)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--out", type=pathlib.Path, default=REPO / "_site")
    parser.add_argument(
        "--outputs",
        type=pathlib.Path,
        default=pathlib.Path(os.environ.get("IRSIM_OUTPUTS", REPO / "outputs")),
        help="the render tree the gallery draws on (default: outputs/, or $IRSIM_OUTPUTS)",
    )
    parser.add_argument("--no-media", action="store_true", help="skip the gallery encode")
    parser.add_argument("--serve", action="store_true", help="serve the result on localhost")
    parser.add_argument("--port", type=int, default=8000)
    args = parser.parse_args()

    result = build(args.out, args.outputs, media=not args.no_media)
    print(
        f"{result['pages']} pages, {result['media']} media files "
        f"({result['media_bytes'] / 1e6:.1f} MB re-encoded from "
        f"{result['source_bytes'] / 1e6:.1f} MB), {result['bytes'] / 1e6:.1f} MB total → {args.out}"
    )
    for source, href in result["unresolved"]:
        print(f"  dead link in {source}: {href}", file=sys.stderr)
    if result["missing"]:
        print(
            f"  {result['missing']} manifest entries were not in {args.outputs} "
            "(listed on the page)"
        )
    print(
        "  preview it with --serve: the in-page search fetches search.json, which a browser "
        "refuses over file://"
    )
    if result["bytes"] > 900e6:
        print("  WARNING: over 900 MB; GitHub Pages publishes about 1 GB", file=sys.stderr)

    if args.serve:
        import functools
        import http.server

        handler = functools.partial(http.server.SimpleHTTPRequestHandler, directory=str(args.out))
        print(f"serving {args.out} on http://localhost:{args.port}/ — ctrl-c to stop")
        http.server.ThreadingHTTPServer(("127.0.0.1", args.port), handler).serve_forever()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
