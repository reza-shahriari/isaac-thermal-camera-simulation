# An overcast night for the vehicle scenes (MP.4). The point of it is what it REMOVES. Under thick
# cloud the sky radiates at close to air temperature, so §5.3's downwelling longwave nearly matches
# what a surface emits and every surface settles within a kelvin or two of ambient regardless of its
# material, its tilt or what it did yesterday. That is the only condition under which a car and the
# asphalt it stands on look the same in LWIR -- which is the first frame the ignition demo needs.
#
# Under a CLEAR night the same scene is not flat at all: the sky is 40-50 K below ambient, every
# upward-facing surface radiates to it and cools, and a car standing over asphalt blocks that cold
# sky and leaves a warm car-shaped patch on the ground (ADR 0088) before its engine has ever run.
# That is the real and well-known phenomenon; it is simply not what a demo of *engine* heat wants
# in frame 0.
#
# No direct beam at all, and the diurnal swing is damped to a third of the clear-sky fixture's,
# which is what thick cloud does to it.
