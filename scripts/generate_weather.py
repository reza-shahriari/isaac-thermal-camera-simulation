# A fair-weather cumulus day, for the scenes whose subject is a target against SKY. The clear
# fixture carries cloud 0.05, which is a sky with nothing in it: `generate_sky_cloud` lays its
# coverage over the whole hemisphere, so at 0.05 a 31 x 25 degree field almost never contains a
# cloud and the "cloud in both bands" claim is untestable on it.
#
# 0.45 is **SCT** in the meteorological sense -- 3-4 oktas, the fair-weather cumulus of a summer
# afternoon -- and it is the interesting condition rather than the extreme one. Overcast (0.98)
# would be easier and would prove nothing: a fully covered sky is a blackbody at air temperature,
# so it has no structure for a detector to false-alarm on and the sun is gone. Broken cloud is
# where a sky-background target is actually hard, because cloud edges are the clutter.
#
# The sun still shines: this is a day of clouds WITH gaps, so the direct beam is only modestly
# reduced and the diffuse component rises, which is what a real broken sky does. Keeping DNI high
# is what lets the aircraft's sunlit skin still separate from its shaded side.
CUMULUS_ARGS: dict[str, float] = {
    "hours": 48.0,
    "utc_offset_h": 2.0,
    "t_mean_k": 294.15,
    "t_swing_k": 9.0,  # broken cloud damps the clear-sky 12 K, but nothing like overcast's third
    "t_max_hour_local": 15.0,
    "dewpoint_k": 286.15,  # RH ~ 0.6 at the afternoon peak: the humidity cumulus needs
    "wind_speed_m_s": 3.5,  # the convective breeze that builds the cumulus in the first place
    "cloud_fraction": 0.45,
    "dni_peak_w_m2": 800.0,
    "dhi_peak_w_m2": 180.0,  # more diffuse than the clear day: cloud sides scatter into the gaps
    "sunrise_hour_local": 5.5,
    "sunset_hour_local": 21.0,
    "visibility_m": 25000.0,
    "step_s": 3600.0,
}
