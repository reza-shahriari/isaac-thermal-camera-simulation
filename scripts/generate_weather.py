def build():  # type: ignore[no-untyped-def]
    from irsim.thermal.weather_io import synthetic_clear_day

    return synthetic_clear_day(SAMPLE_START, **SAMPLE_ARGS)


def build_coastal():  # type: ignore[no-untyped-def]
    from irsim.thermal.weather_io import synthetic_clear_day

    return synthetic_clear_day(COASTAL_START, **COASTAL_ARGS)


def build_overcast():  # type: ignore[no-untyped-def]
    from irsim.thermal.weather_io import synthetic_clear_day

    return synthetic_clear_day(OVERCAST_START, **OVERCAST_ARGS)


def build_cumulus():  # type: ignore[no-untyped-def]
    from irsim.thermal.weather_io import synthetic_clear_day

    return synthetic_clear_day(CUMULUS_START, **CUMULUS_ARGS)


def main() -> int:
    from irsim.thermal.weather_io import write_weather_csv

    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", type=pathlib.Path, default=None)
    ap.add_argument(
        "--which",
        choices=("inland", "coastal", "overcast", "cumulus", "all"),
        default="all",
        help="inland is the original M6.2 fixture; coastal is the sea-breeze day the maritime "
        "scenes need (MM.6); overcast is the flat still night the MP.4 vehicle demo needs; "
        "cumulus is the broken sky a sky-background target is actually hard against",
    )
    args = ap.parse_args()

    jobs = []
    if args.which in ("inland", "all"):
        jobs.append((build(), args.out or DEFAULT_OUT, SAMPLE_COMMENT))
    if args.which in ("coastal", "all"):
        jobs.append((build_coastal(), args.out or COASTAL_OUT, COASTAL_COMMENT))
    if args.which in ("overcast", "all"):
        jobs.append((build_overcast(), args.out or OVERCAST_OUT, OVERCAST_COMMENT))
    if args.which in ("cumulus", "all"):
        jobs.append((build_cumulus(), args.out or CUMULUS_OUT, CUMULUS_COMMENT))
    if args.out is not None and len(jobs) > 1:
        ap.error("--out names one file, so pass a single --which with it")

    for series, out, comment in jobs:
        out.parent.mkdir(parents=True, exist_ok=True)
        write_weather_csv(series, out, comment=comment)
        print(f"wrote {out} ({series.n} rows, hash {series.content_hash[:12]})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
